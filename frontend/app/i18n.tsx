function interpolate(template: string, params?: Params) {
  return Object.entries(params ?? {}).reduce((value, [key, item]) => value.replaceAll(`{${key}}`, String(item)), template);
}

const I18nContext = createContext<I18nContextValue | null>(null);

function detectedLanguage(): Language {
  const stored = window.localStorage.getItem("shcr-language");
  return stored === "en" || stored === "id"
    ? stored
    : navigator.language.toLowerCase().startsWith("en")
      ? "en"
      : "id";
}

function localizedUrl(url: string, lang: Language) {
  const parsed = new URL(url, "http://localhost");
  parsed.searchParams.set("lang", lang);
  return /^https?:\/\//i.test(url)
    ? parsed.toString()
    : `${parsed.pathname}${parsed.search}${parsed.hash}`;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLanguage] = useState<Language>("id");
  const [ready, setReady] = useState(false);
  useEffect(() => {
    const detected = detectedLanguage();
    setLanguage(detected);
    document.documentElement.lang = detected;
    setReady(true);
  }, []);
  const setLang = (next: Language) => {
    setLanguage(next);
    window.localStorage.setItem("shcr-language", next);
    document.documentElement.lang = next;
  };
  const value = useMemo<I18nContextValue>(() => ({
    lang,
    setLang,
    t: (key, params) => interpolate(messages[lang][key] ?? messages.en[key] ?? key, params),
    query: (url) => localizedUrl(url, lang),
    formatNumber: (number, options) => new Intl.NumberFormat(lang === "id" ? "id-ID" : "en-US", options).format(number),
    formatDateTime: (date) => new Intl.DateTimeFormat(lang === "id" ? "id-ID" : "en-US", { dateStyle: "medium", timeStyle: "medium" }).format(new Date(date)),
  }), [lang]);
  if (!ready) return null;
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
